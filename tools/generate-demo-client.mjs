import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const toolDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(toolDir, "..");
const sourcePath = resolve(repoRoot, "supabase/functions/demo-data/index.ts");
const outputPath = resolve(repoRoot, "src/lib/demo-data-client.ts");
const source = readFileSync(sourcePath, "utf8");
const helpersStart = source.indexOf("function daysAgo");

if (helpersStart < 0) {
  throw new Error("demo-data helpers were not found");
}

const clientSource = source
  .slice(helpersStart)
  .replace("async function runSeed", "export async function runDemoSeed")
  .replace("await runCleanup(supabase);", "await runDemoCleanup(supabase);")
  .replace("async function runCleanup", "export async function runDemoCleanup");

writeFileSync(
  outputPath,
  `// Generated by tools/generate-demo-client.mjs from the Supabase demo-data function.\n${clientSource}`,
  "utf8",
);
